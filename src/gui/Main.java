    private void mostrarAlertaEnTabla() {
        modeloPendientes.setRowCount(0); //limpiamos tabla
        String estado = "En proceso";
        NodoExpediente nodoInicio = admin.getListaAlerta().inicio;
        
        nodoActual = nodoInicio;
        if(nodoActual == null) {
            System.out.println("nulo");
        return;}
        
        while(nodoActual.siguiente != nodoInicio){
            Expediente e = nodoActual.getDato();
            
            modeloPendientes.addRow(new Object[] {
                e.getId(),
                e.getPrioridad(),
                e.getInteresado().getNombres(),
                e.getFechaInicio().toString(),
                estado
            });
            
            nodoActual = nodoActual.siguiente;
        }
        
        //agregar ultimo dato
        Expediente e = nodoActual.getDato();
        modeloPendientes.addRow(new Object[]{
            e.getId(),
            e.getPrioridad(),
            e.getInteresado().getNombres(),
            e.getFechaInicio().toString(),
            estado
        });
}   
