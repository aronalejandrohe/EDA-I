    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed
        // TODO add your handling code here:

        String id = this.jTextField4.getText();
        if(id.isEmpty() != true){
            Expediente e = admin.getArbol().buscar(id);
            if(e != null){
                movimientoTabla.setRowCount(0);
                NodoSimple actual = e.getListaMovimientos().primero;
                while(actual != null){
                    String nombreDependencia = actual.elemento.getDependencia().getNombre();
                    String codigoDependencia = actual.elemento.getDependencia().getCodigo();
                    String fechaMovimiento = actual.elemento.getFecha().toString();
                    movimientoTabla.addRow(new Object[]{
                        id,
                        fechaMovimiento,
                        nombreDependencia,
                        codigoDependencia
                    });
                    actual=actual.siguiente;
                }

            }
            else{
                javax.swing.JOptionPane.showMessageDialog(this, "Movimientos para el Expediente no encontrados");
            }
        }
    }//GEN-LAST:event_jButton9ActionPerformed

