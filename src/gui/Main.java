    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        // TODO add your handling code here:
        String id = this.jTextField9.getText();
        String nombre = this.jComboBox2.getSelectedItem().toString();
        String codigo="";

        if (nombre.equals("Biblioteca Central")){
            codigo = "DEP001";
            System.out.println("dep001");
        } else if (nombre.equals("Oficina de Admisión")) {
            codigo = "DEP002";
        } else if (nombre.equals("Secretaría Académica")) {
            codigo = "DEP003";
        } else if (nombre.equals("Centro de Cómputo")) {
            codigo = "DEP004";
        } else if (nombre.equals("Dirección General")) {
            codigo = "DEP005";
        }

        Dependencia dependencia = new Dependencia(nombre,codigo);
        boolean terminado = false;
        if (id.isEmpty() != true && dependencia != null) {

            if(admin.getArbol().buscar(id).getFechaFin() != null){
                terminado=true;
            }

            if(terminado==true){
                javax.swing.JOptionPane.showMessageDialog(this, "Movimiento no registrado: trámite ya finalizado");
            }
            else{

                Seguimiento s = new Seguimiento(dependencia);
                admin.movimientoAgregar(id, s);
                javax.swing.JOptionPane.showMessageDialog(this, "Movimiento registrado correctamente.");
            }
        }
        else {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe ingresar el ID y seleccionar una dependencia.");
        }
    }//GEN-LAST:event_jButton7ActionPerformed

